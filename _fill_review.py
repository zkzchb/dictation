def main():
    wb = load_workbook(XLSX)

    # 1) lesson 表补 8 个复习课
    ls = wb["lesson"]
    existing = {ls.cell(r, 1).value for r in range(1, ls.max_row + 1)}
    row = ls.max_row + 1
    added_l = 0
    for lid, title, name in REVIEW_LESSONS:
        if lid in existing:
            continue
        ls.cell(row, 1, lid); ls.cell(row, 2, title); ls.cell(row, 3, name)
        row += 1; added_l += 1

    # 2) typo 表：清空数据行后重写（保留表头）
    tp = wb["typo"]
    for r in range(tp.max_row, 1, -1):
        tp.delete_rows(r)
    row = 2
    n_typo = 0
    for lid in sorted(TYPO):
        for i, (ch, w1, p1, w2, p2) in enumerate(TYPO[lid], start=1):
            tp.cell(row, 1, lid * 100 + i)
            tp.cell(row, 2, ch)
            tp.cell(row, 3, w1); tp.cell(row, 4, p1)
            tp.cell(row, 5, w2); tp.cell(row, 6, p2)
            row += 1; n_typo += 1

    # 3) vocab 表：追加搭配与分类（不动已有 250 词）
    vc = wb["vocab"]
    seen = set()
    for r in range(2, vc.max_row + 1):
        v = vc.cell(r, 3).value
        if v:
            seen.add(str(v).strip())
    row = vc.max_row + 1
    n_voc = 0
    for lid in sorted(set(COLLOC) | set(CLASSIFY)):
        seq = 51
        for w in COLLOC.get(lid, []):
            if w in seen:
                continue
            vc.cell(row, 1, lid * 100 + seq); vc.cell(row, 2, "搭配")
            vc.cell(row, 3, w)
            row += 1; seq += 1; n_voc += 1; seen.add(w)
        for vtype, words in CLASSIFY.get(lid, []):
            for w in words:
                if w in seen:
                    continue
                vc.cell(row, 1, lid * 100 + seq); vc.cell(row, 2, vtype)
                vc.cell(row, 3, w)
                row += 1; seq += 1; n_voc += 1; seen.add(w)

    wb.save(XLSX)
    print(f"[OK] lesson 新增复习课 {added_l}")
    print(f"[OK] typo  写入易混字 {n_typo} 组")
    print(f"[OK] vocab 追加搭配/分类 {n_voc} 条（拼音待补）")


if __name__ == "__main__":
    main()
